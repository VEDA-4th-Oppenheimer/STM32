  motor_init();                            // 축 드라이버 (전류 차단 상태로 시작)
  scan_init();                             // 스캔 시퀀서
  lidar_init(&huart6);                     // USART6(라이다) 수신 시작

  // Pan(TIM1) / Tilt(TIM2) 타이머 인터럽트 시작.
