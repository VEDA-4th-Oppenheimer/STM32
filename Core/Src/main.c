  //   TIM1 : 84MHz/84/5000 = 200Hz  (Pan)
  //   TIM2 : 84MHz/84/2500 = 400Hz  (Tilt, 0.1125도/펄스 -> 45도/s)
  // 틐트 45도/s + 라이다 100Hz = 0.45도/샘플 = 정확히 4 마이크로스텝.
