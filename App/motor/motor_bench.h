/* ============================================================================
 *  motor_bench.h  --  모터 축 단독 왕복 테스트 (임시 브링업 도구)
 * ----------------------------------------------------------------------------
 *  담당: 이현우
 *
 *  "축이 안 도는데 코드 문제냐 하드웨어 문제냐" 를 **측정으로** 가른다.
 *
 *  스캔 시퀀서·라이다·데몬을 전부 우회하고 두 축에 직접 목표를 주며 왕복시킨다.
 *  그래서 링크가 죽어 있어도, 라이다가 없어도, 홈이 안 잡혀도 돌아간다.
 *
 *  ★ 핵심 판별 ★
 *    axis_step() 은 펄스를 낼 때마다 rt->pulse 를 증감한다. 즉 화면의 pulse 가
 *    올라간다는 것은 **ISR 이 실제로 STEP 핀을 토글했다**는 뜻이다. 그러므로:
 *
 *      pulse 가 오른다 + 축이 안 움직인다  ->  펌웨어는 결백. 하드웨어 문제
 *                                             (VMOT / 드라이버 모듈 / Vref /
 *                                              nSLEEP·nRESET / 제어선 배선)
 *      pulse 가 안 오른다                  ->  타이머·ISR·목표설정 쪽 문제
 *
 *    별도 카운터를 만들지 않은 이유는 실제 구동 경로가 쓰는 바로 그 변수를
 *    봐야 의미가 있기 때문이다. 따로 세면 "카운터만 도는" 착시가 생긴다.
 *
 *  EN 핀 레벨도 같이 찍는다(active-low 라 구동 중엔 0 이어야 한다). 3.3V 로
 *  읽히면 enable 이 안 걸린 것이고, 그건 배선이 옛 핀맵에 꽂혀 있다는 신호다.
 *
 *  ⚠️ 브링업 전용. 켜면 스캔 명령을 무시하고 축을 제멋대로 움직이므로
 *    **데모/실측 전에 반드시 0 으로 되돌릴 것**. 켜면 빌드마다 #warning 이 뜬다.
 * ==========================================================================*/
#ifndef MOTOR_BENCH_H
#define MOTOR_BENCH_H

/* ===========================================================================
 *          ★★  바로 아래 값을  0 ↔ 1  로 바꾸면 된다  ★★
 *              0 = 꺼짐 (정상 동작, 코드가 통째로 컴파일아웃)
 *              1 = 두 축을 왕복시키며 pulse/target/EN 을 VCP 로 출력
 * ========================================================================= */
#ifndef MOTOR_BENCH_TEST       /* -DMOTOR_BENCH_TEST=1 로도 켤 수 있다 */
#define MOTOR_BENCH_TEST   1   /* ★ 여기 ★ */
#endif

#if MOTOR_BENCH_TEST
#warning "MOTOR_BENCH_TEST=1 : 모터 왕복 테스트 활성(브링업 전용). 스캔 전 0 으로 되돌릴 것"

/* ===========================================================================
 *          ★★  어느 축을 돌릴지 —  0 / 1 / 2  ★★
 *              0 = 두 축 동시
 *              1 = 팬만
 *              2 = 틸트만
 *
 *  한 축만 돌리면 소리·진동으로 어느 쪽인지 확실히 구분된다. 두 축을 같이
 *  돌리면 한쪽만 돌아도 "돌고 있다"고 오인하기 쉽다.
 *
 *  ⚠️ 쉬는 축도 EN 은 계속 LOW(전류 인가) 로 둔다. 그래야 손으로 만졌을 때
 *    "전류는 오는데 안 움직이는지" 를 구분할 수 있다. 목표만 현재 위치로
 *    고정해 펄스가 안 나가게 한다.
 * ========================================================================= */
#ifndef MOTOR_BENCH_AXIS       /* -DMOTOR_BENCH_AXIS=2 로도 지정 가능 */
#define MOTOR_BENCH_AXIS   0   /* ★ 여기 ★ */
#endif

/* 왕복 진폭(도) 와 반전 주기(ms). 좁게 잡아 기구 충돌을 피한다.
 * ⚠️ #if 안에 둔다 — 밖에 두면 꺼진 빌드에서 "안 쓰이는 매크로"(MISRA 2.5)가 된다. */
#define MOTOR_BENCH_SWING_DEG   15
#define MOTOR_BENCH_FLIP_MS     4000u
#endif

/* 메인루프에서 매 바퀴 호출한다. 꺼져 있으면 아무것도 하지 않는다. */
void motor_bench_run(void);

#endif /* MOTOR_BENCH_H */
