/* ============================================================================
 *  hallEffectSensor.h  --  MT6701 자기 각도 엔코더 I2C 판독
 * ----------------------------------------------------------------------------
 *  담당: 강유근 (원 구현) / 이현우 (NULL 가드·타임아웃·주석 교정)
 *
 *  주의: 파일 이름이 "hallEffectSensor" 지만 홀 스위치가 아니라 **MT6701 자기
 *    각도 엔코더**다(내부 감지 소자가 홀이라 붙은 이름). 리밋스위치 같은
 *    on/off 센서와 헷갈리지 말 것 — 이 프로젝트에 리밋스위치는 없다.
 *
 *  MT6701:
 *    14비트 절대 엔코더. 0 ~ 16383 이 한 바퀴(360도)에 대응하므로 분해능은
 *    360/16384 = 0.022도. 1/16 마이크로스텝 1 스텝이 0.1125도이니 엔코더가
 *    스텝보다 5배 촘촘하다 — 1 스텝 탈조도 검출할 수 있다.
 *
 *    I2C 주소가 0x06 고정이라 축마다 버스를 나눠 쓴다:
 *      Pan  = I2C3 (PA8 SCL / PC9 SDA)
 *      Tilt = I2C1 (PB8 SCL / PB9 SDA)
 *    어느 축인지는 호출자가 핸들로 구분한다(App/motor 의 motor_read_encoder).
 *
 *  용도(protocol.h §4): 홈 확립 / 틸트 줄 끝 대조 / 팬 줄 시작 검증.
 *  스캔 중 샘플마다 읽지는 않는다 — I2C 판독이 끝난 시각과 라이다 샘플
 *  시각이 달라 오히려 동기 오차가 생기기 때문.
 * ==========================================================================*/
#ifndef HALL_EFFECT_SENSOR_H
#define HALL_EFFECT_SENSOR_H

/* STM32F4 HAL 라이브러리 헤더 */
#include "stm32f4xx_hal.h"

/* -------------------------------------------------------------------------- */
/* MT6701 I2C 매크로 설정                                                     */
/* -------------------------------------------------------------------------- */
#define MT6701_ADDR   ((uint16_t)0x0CU)     /* 7비트 0x06 을 HAL 규약(<<1)으로 */
#define REG_ANGLE_14B ((uint16_t)0x03U)     /* 각도 레지스터 시작 (0x03,0x04)  */

/* 통신 타임아웃(ms).
 * 400kHz 에서 2바이트 판독은 약 0.13ms 라 10ms 도 75배 여유다.
 * 길게 잡으면(예전 100ms) 센서가 죽었을 때 메인루프가 그만큼 멈추고,
 * 재시도 5회까지 겹치면 0.5초를 넘겨 라이다 샘플 큐(80ms 여유)가 넘친다. */
#define I2C_TIMEOUT   ((uint32_t)10U)

/* -------------------------------------------------------------------------- */
/* 데이터 구조체 정의                                                         */
/* -------------------------------------------------------------------------- */
typedef struct {
    uint16_t raw_angle;  /* 14비트 원본 (0 ~ 16383)      */
    float    degree;     /* 환산 각도 (0.0 ~ 359.978도)  */
} Encoder_t;

/* MT6701 에서 각도를 1회 판독한다 (블로킹).
 *
 *   hi2c         : 축에 해당하는 I2C 핸들 (Pan=&hi2c3 / Tilt=&hi2c1)
 *   encoder_data : 결과 저장 위치
 *   반환         : HAL_OK 면 encoder_data 유효
 *
 * 주의: 실패 시 encoder_data 를 건드리지 않는다. 호출자는 반환값을 반드시
 *   확인할 것 — 확인하지 않으면 이전 판독값(또는 초기화 안 된 값)을 현재
 *   각도로 오인한다. 홈에서 이걸 놓치면 축이 실제로는 움직이지 않았는데
 *   "홈 완료" 가 되는 사고로 이어진다.
 *
 * 주의: 블로킹이므로 ISR 에서 호출하지 말 것 (메인루프 전용). */
HAL_StatusTypeDef Encoder_Read(I2C_HandleTypeDef *hi2c, Encoder_t *encoder_data);

/* I2C 페리페럴을 되살린다 (DeInit + Init).
 *
 * 핵심: 왜 필요한가 — 실기에서 확인된 것:
 *   타임아웃이나 NACK 이 **한 번** 나면 STM32 HAL 의 I2C 가 상태를 래치한다
 *   (hi2c->State 가 BUSY_TX 에 걸리거나 BUSY 플래그가 남는다). 그러면 이후
 *   모든 호출이 즉시 HAL_BUSY 로 튕겨서 **리셋 전까지 영영 실패**한다.
 *   증상: DISARM 뒤 홈을 다시 걸면 엔코더가 안 읽히고, STM32 를 리셋해야만
 *   돌아온다.
 *
 * 주의: 슬레이브가 SDA 를 붙잡은 경우는 이걸로 안 풀린다(그때는 SCL 을 9번
 *   토글해 클럭 아웃시켜야 한다). 하지만 우리 증상은 **MCU 리셋만으로**
 *   복구됐다 — MCU 리셋은 클럭을 내보내지 않으므로, 슬레이브가 붙잡고
 *   있었다면 그걸로 안 풀렸을 것이다. 즉 원인은 STM32 쪽 상태 하나뿐이고
 *   DeInit/Init 으로 충분하다. 9클럭 복구는 필요해지면 그때 넣는다.
 *
 * 비용은 수백 us 다. 실패했을 때만 부른다. */
HAL_StatusTypeDef Encoder_BusRecover(I2C_HandleTypeDef *hi2c);

#endif /* HALL_EFFECT_SENSOR_H */
