/* ============================================================================
 *  encoder_bench.h  --  MT6701 엔코더 벤치 판독 (임시 브링업 도구)
 * ----------------------------------------------------------------------------
 *  담당: 이현우
 *
 *  두 축의 엔코더를 주기적으로 읽어 VCP(USART2) 로 찍는다. 목적은 두 가지다:
 *
 *    ① 배선 확인 — I2C3(Pan: PA8/PC9) / I2C1(Tilt: PB8/PB9) 가 실제로
 *       응답하는지. 축을 손으로 돌렸을 때 숫자가 따라 움직이면 정상이다.
 *
 *    ② 영점 상수 실측 — MOTOR_PAN_ZERO_OFFSET_DEG / MOTOR_TILT_ZERO_OFFSET_DEG.
 *       리밋스위치를 쓰지 않으므로 좌표계 전체가 이 두 상수에 의존한다.
 *       규약은 motor.c 의 motor_encoder_deg_to_pulse 가 정한다:
 *
 *           기구각 = 엔코더 실측각 − zero_offset_deg
 *
 *       따라서 축을 **기준 자세**(팬=기준 방위 / 틸트=바닥 nadir)에 맞춰 놓고
 *       읽은 각도가 **그대로 영점 상수**다. 화면의 "→ OFFSET" 값을 motor.h 에
 *       옮겨 적으면 된다.
 *
 *  ⚠️ 이건 브링업 도구다. 켜면 100ms 마다 블로킹 I2C 판독 2회 + printf 를
 *    하므로 **스캔 중에는 절대 켜두지 말 것** — 라이다 프레임을 잃는다.
 *    (그래서 켜면 빌드마다 #warning 이 뜬다)
 * ==========================================================================*/
