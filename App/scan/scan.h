/* ============================================================================
 *  scan.h  --  2축 스캔 시퀀서
 * ----------------------------------------------------------------------------
 *  담당: 이현우
 *
 *  ★ 메인루프에서 도는 시퀀서다. ISR 이 아니다.
 *    그래서 여기서는 블로킹 I2C(엔코더)도 HAL_Delay 도 안전하다.
 *    반대로 motor 계층(App/motor)은 ISR 에서 펄스만 내고 아무 판단도 하지
 *    않는다. 이전 구현이 시퀀서를 ISR 안에 두는 바람에 ISR 에서 HAL_Delay·
 *    printf·I2C 를 하게 됐고 데드락과 라이다 프레임 유실을 낳았다.
 *
 *  스캔 구조 (천장 마운트 2축):
 *    틸트 = 빠른 축. 한 줄이 -90 -> +90 (한쪽 벽 -> 바닥 -> 반대쪽 벽).
 *    팬   = 느린 축. 줄마다 step_ddeg 만큼. 스윕 동안은 정지.
 *    줄마다 틸트 방향을 뒤집는다(serpentine) — 되감기가 필요 없어진다.
 *
 *  각도는 전부 **기구각**이다. 계약 좌표계 변환은 RPi 데몬 몫
 *  (protocol.h §4). 펌웨어는 모터가 어디 있는지만 정직하게 보고한다.
 *
 *  엔코더 사용처 (protocol.h §4 와 동일):
 *    ① 홈 확립 — 절대 엔코더라 구동 없이 읽기 1회
 *    ② 틸트 줄 끝(±90) 대조 — 방향 전환이 탈조가 나는 자리라 재영점
 *    ③ 팬 줄 시작 대조 — 보정 없이 검증만 (보정 이동이 새 실패 모드가 됨)
 * ==========================================================================*/
#ifndef SCAN_H
#define SCAN_H

#include "main.h"
#include "protocol.h"
#include <stdbool.h>
#include <stdint.h>

/* ===========================================================================
 *  🔧 임시 브링업 스위치 — 엔코더(MT6701) 없이 스캔
 * ---------------------------------------------------------------------------
 *
 *          ★★  바로 아래 값을  0 ↔ 1  로 바꾸면 된다  ★★
 *              0 = 정상 (엔코더 사용)
 *              1 = 브링업 (엔코더 미사용, 개루프)
 *
 * ---------------------------------------------------------------------------
 *  1 일 때 달라지는 것:
 *      · 홈       : 판독 없이 "지금 있는 자리가 기구각 0" 이라고 선언한다.
 *      · 줄 끝/줄 시작 대조 : 건너뛴다(호출 자체를 안 한다).
 *
 *  기구물이나 엔코더 배선이 아직 없을 때 스캔 경로 전체(모터→라이다→각도
 *  래치→상행→격자→산출물)를 돌려보기 위한 것이다.
 *
 *  ⚠️ 켜면 **탈조를 검출할 수단이 완전히 사라진다.** 스텝카운트가 곧 진실인
 *    개루프가 되므로 산출물의 각도는 "명령한 각도"일 뿐 실제 각도가 아니다.
 *  ⚠️ 스캔 시작 전에 두 축을 **물리적으로 기준 자세에 맞춰 둘 것**
 *    (틸트 = 바닥 nadir / 팬 = 기준 방위). 안 맞추면 산출물이 통째로 틀어진다.
 *  ⚠️ CMD_HOMED 의 엔코더 raw 를 0xFFFF 로 보낸다 — 14비트 엔코더가 낼 수
 *    없는 값(최대 16383)이라, 산출물만 봐도 "엔코더 없이 찍은 스캔" 임을
 *    구분할 수 있다. 0 을 보내면 정상 판독값과 섞여 구분이 안 된다.
 *  ⚠️ **데모/최종본 전에 반드시 0 으로 되돌릴 것.**
 * ========================================================================= */
#ifndef SCAN_NO_ENCODER          /* -DSCAN_NO_ENCODER=1 로 덮어쓸 수도 있다 */
#define SCAN_NO_ENCODER   1      /* ★ 여기 ★   0 = 정상 / 1 = 엔코더 없이  */
#endif

#if SCAN_NO_ENCODER
#warning "SCAN_NO_ENCODER=1 : 엔코더 없이 개루프 스캔(브링업 전용). 탈조 검출 불가 — 데모 전 0 으로 되돌릴 것"
#endif

/* --- 엔코더 대조 임계 -----------------------------------------------------
 *  MT6701 해상도가 0.022도, 1 스텝이 0.1125도 이므로 0.3도(=약 3스텝)면
 *  측정 잡음이 아니라 실제 탈조로 볼 수 있다.
 *  2.0도를 넘으면 기구 이상이다 — 계속해봐야 쓰레기 데이터라 중단한다. */
/* ===========================================================================
 *          ★★  스캔 방식 —  0 / 1  ★★
 *              0 = 연속 스윕 (틸트를 멈추지 않고 훑으며 라이다 도착 순간 각도 래치)
 *              1 = step-and-shoot (한 점씩 이동→정착→측정)
 *
 *  step-and-shoot 이 해결하는 것:
 *    - 샘플 간격과 격자의 불일치 (연속 스윕은 틸트속도/라이다레이트로 정해져
 *      격자의 정수 약수가 아니면 빈 셀과 중복이 생긴다. 7/30 실측 365/2789건)
 *    - 스미어 (측정 중 빔이 훑고 지나가 에지가 뭉개진다)
 *  대가는 시간이다. 점당 (이동 + 정착 + 프레임대기) 가 붙는다.
 *
 *  ⚠️ 라이다는 액티브 출력이라 "지금 재라" 를 시킬 수 없다. 그래서 정착 후
 *    **다음 유효 프레임 하나만 취하고 나머지는 버린다**. 프레임은 10ms 마다
 *    공짜로 오므로 버리는 비용은 0 이다.
 * ========================================================================= */
#ifndef SCAN_STEP_AND_SHOOT
#define SCAN_STEP_AND_SHOOT   1   /* ★ 여기 ★ */
#endif

#if SCAN_STEP_AND_SHOOT
/* 정착 대기(ms). 이동을 멈춘 뒤 기구 링잉이 잦아들기를 기다리는 시간.
 *
 * ⚠️ 이 값이 전체 스캔 시간을 좌우한다 — 반드시 실측해서 정할 것.
 *   빔 FOV 가 1~2도라 링잉이 그 몇 %면 측정에 영향이 없다. 즉 "완전히
 *   멈출 때까지" 가 아니라 "빔 폭 대비 무시할 만큼" 이면 충분하다.
 *
 *   점당 예산 = 이동(8펄스/pps) + 정착 + 프레임대기(최대 10ms @100Hz)
 *   예) 400pps 이동 20ms + 정착 25ms + 프레임 15ms = 60ms
 *       -> 틸트 +-70도 156점이면 한 줄 9.4초 */
#define SCAN_SETTLE_MS        25u

/* 캡처 무장 후 프레임이 안 오면 포기할 시한(ms).
 * 라이다가 죽었을 때 한 점에서 영원히 멈추는 걸 막는다. 100Hz 면 10ms 마다
 * 오므로 이 값을 넘겼다는 건 수신이 끊겼다는 뜻이다. */
#define SCAN_CAPTURE_TIMEOUT_MS  200u
#endif

#define SCAN_RESYNC_DDEG      3     /* 0.3도 — 넘으면 재영점        */
#define SCAN_STALL_DDEG      20     /* 2.0도 — 넘으면 ERR_STALL     */

typedef enum {
    SC_IDLE = 0,
    SC_HOMING,       /* 엔코더 판독으로 절대 위치 확립 (구동 없음) */
    SC_MOVE_START,   /* 스캔 시작점으로 이동                        */
    SC_SWEEP,        /* 틸트 스윕 진행 중 — 이 구간의 점만 유효     */

    /* --- step-and-shoot 전용 (SCAN_STEP_AND_SHOOT=1 일 때만 쓰인다) ------
     *  연속 스윕과 달리 한 점씩 "이동 → 정착 → 측정" 을 반복한다. */
    SC_STEP_MOVE,    /* 다음 격자점으로 8펄스 이동 중                 */
    SC_STEP_SETTLE,  /* 정착 대기 (기구 링잉이 잦아들기를)            */
    SC_STEP_CAPTURE, /* 캡처 무장 — 다음 유효 프레임 하나만 취한다    */

    SC_LINE_END,     /* 줄 끝: 틸트 엔코더 대조 + 재영점            */
    SC_PAN_STEP,     /* 팬 1스텝 이동 + 팬 엔코더 검증              */
    SC_DONE          /* 완료 통지 후 IDLE                            */
} scan_state_t;

void scan_init(void);

/* CMD_HOME / CMD_SCAN_START / CMD_SCAN_STOP 진입점 (uart_rpi 디스패처가 호출) */
void scan_home(void);
void scan_start(const struct proto_scan_start *ss);
void scan_stop(void);

/* 메인루프에서 매 바퀴 호출. 상태 전이와 엔코더 판독이 전부 여기서 일어난다. */
void scan_process(void);

bool         scan_is_busy(void);
scan_state_t scan_get_state(void);

/* --- 라이다 연동 (App/lidar 가 호출) --------------------------------------
 *
 *  각도-거리 짝짓기는 **STM32 안에서 원자적으로 끝나야** 한다. 프레임이
 *  완성된 순간의 각도를 잡아 두고, 파싱이 끝난 뒤 그 각도와 함께 제출한다.
 *  RPi 로는 이미 짝지어진 (pan, tilt, d) 가 올라가므로 연관 부담이 없다.
 *
 *  ① 라이다 UART ISR 에서 프레임 마지막 바이트를 받은 즉시:
 *        scan_latch_angles(&pan, &tilt);
 *     (모터 카운터를 읽기만 하므로 ISR 에서 안전하다)
 *
 *  ② 메인루프에서 프레임 파싱이 끝나면 ①의 각도와 함께:
 *        scan_submit_sample(pan, tilt, d_mm, ...);
 *
 *  스윕 구간(SC_SWEEP)이 아닐 때 들어온 샘플은 버린다 — 줄 끝 정지나
 *  팬 이동 중의 점은 격자에 넣을 각도가 아니기 때문. */
void scan_latch_angles(int16_t *out_pan_ddeg, int16_t *out_tilt_ddeg);

void scan_submit_sample(int16_t pan_ddeg, int16_t tilt_ddeg,
                        uint16_t d_mm, uint16_t signal_strength,
                        uint32_t device_time_ms,
                        uint8_t dis_status, uint8_t range_precision);

#endif /* SCAN_H */
